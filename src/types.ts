// ========== Undo/Redo 関連 ==========

export type TimetableOpType =
  | 'timetable:autoSchedule'
  | 'timetable:resetAll'
  | 'entry:add'
  | 'entry:delete'
  | 'entry:reorder'
  | 'cool:add'
  | 'cool:delete'
  | 'cool:startTime';

export type BandOpType = 'band:add' | 'band:delete' | 'band:update';

export type CustomFieldsOpType =
  | 'customCell:set'
  | 'customCell:merge'
  | 'customCell:unmerge'
  | 'customColumn:add'
  | 'customColumn:delete'
  | 'customColumn:rename'
  | 'customColumn:reorder'
  | 'customColumn:visibility'
  | 'customColumn:shared'
  | 'customColumn:shift';

export type OperationType = TimetableOpType | BandOpType | CustomFieldsOpType;

export interface UndoRecord {
  id: string;
  sessionId: string;
  timestamp: number;
  targetId: string;
  opType: OperationType;
  invalidated: boolean;
  undo: () => Promise<void>;
  redo: () => Promise<void>;
  // direction: 'undo' なら現在の状態が「適用後(after)」と一致するか、
  // 'redo' なら現在の状態が「適用前(before)」と一致するかを確認する
  isConflicted: (direction: 'undo' | 'redo') => boolean;
}

export interface SkippedOpInfo {
  opType: OperationType;
  reason: 'external' | 'cascade';
}

export interface BandUndoMeta {
  opType: BandOpType;
  before: Band | null;
  after: Band | null;
}

export interface CustomFieldsUndoMeta {
  opType: CustomFieldsOpType;
  targetId: string;
  before: CustomFieldsSettings;
  after: CustomFieldsSettings;
}
